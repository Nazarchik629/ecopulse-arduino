-- Выполнить один раз в Supabase: SQL Editor -> New query -> Run.
create table if not exists public.readings (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  temperature real not null check (temperature between -40 and 85),
  humidity real not null check (humidity between 0 and 100)
);

-- Если использовалась прежняя версия схемы с необязательным световым каналом,
-- оставляем его старые значения в базе, но разрешаем новым строкам не передавать свет.
do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'readings' and column_name = 'light'
  ) then
    alter table public.readings alter column light drop not null;
  end if;
end;
$$;

alter table public.readings enable row level security;

