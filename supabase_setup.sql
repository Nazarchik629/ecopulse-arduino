drop function if exists public.ingest_reading(text, real, real, real);
create or replace function public.ingest_reading(
  p_token text, p_temperature real, p_humidity real
) returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not exists (
    select 1 from private.device_secrets
    where id = 1 and token = p_token
  ) then
    raise exception 'Invalid device token';
  end if;
  insert into public.readings (temperature, humidity)
  values (p_temperature, p_humidity);
end;
$$;
revoke all on function public.ingest_reading(text, real, real) from public;
grant execute on function public.ingest_reading(text, real, real) to anon;

-- Сайт читает готовую дневную сводку, а не десятки тысяч отдельных измерений.
drop view if exists public.daily_readings;
create view public.daily_readings
with (security_invoker = true)
as
select
  (created_at at time zone 'Asia/Qyzylorda')::date as day,
  count(*)::integer as sample_count,
  avg(temperature)::real as temperature,
  min(temperature)::real as temperature_min,
  max(temperature)::real as temperature_max,
  avg(humidity)::real as humidity,
  min(humidity)::real as humidity_min,
  max(humidity)::real as humidity_max
from public.readings
where created_at >= now() - interval '10 days'
group by (created_at at time zone 'Asia/Qyzylorda')::date;
grant select on public.daily_readings to anon;
